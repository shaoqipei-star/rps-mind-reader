_LEVEL = {"#": 255, "+": 40, ".": 0}


def icon_bytes(name: str) -> bytes:
    """把圖示轉成 104 個位元組（每顆 LED 的亮度 0~255），給 MCU 的 draw() 用。"""
    rows = _ICONS[name]
    assert len(rows) == ROWS and all(len(r) == COLS for r in rows), name
    return bytes(_LEVEL[c] for row in rows for c in row)


def names():
    return list(_ICONS)
